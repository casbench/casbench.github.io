# Table of bench G (included by make_tables.jl).
#
# Output: tables/G_groebner.tex, one row per case: the warm time of each
# system when its basis is verified (else its status), the size of the basis
# and the agreement: how many of the systems that answered share the canonical
# digest written in the note by the check (a reduced Gröbner basis is unique).

const G_SYSTEMS = ["giac", "groebner", "msolve", "sympy", "sage_singular", "sage_giac", "macaulay2"]
const G_LABEL = Dict("giac" => "Giac.jl", "groebner" => "Groebner.jl", "msolve" => "msolve", "sympy" => "SymPy",
                     "sage_singular" => "Sage/Singular", "sage_giac" => "Sage/Giac", "macaulay2" => "Macaulay2")

function make_G()
    data = Dict(s => read_records(joinpath(RESULTS, "G_groebner_$(s).tsv")) for s in G_SYSTEMS)
    any(!isempty, values(data)) || return
    cases = String[]
    for s in G_SYSTEMS, r in data[s]
        r.case == "_load" && continue
        r.case in cases || push!(cases, r.case)
    end
    rec(s, c) = (j = findfirst(r -> r.case == c, data[s]); j === nothing ? nothing : data[s][j])
    digest(r) = (m = match(r"sha=([0-9a-f]+)", r.note); m === nothing ? "" : m[1])
    ksize(r) = (m = match(r"k=(\d+)", r.note); m === nothing ? "" : m[1])
    cell(r) = r === nothing ? "--" :
        r.status == "verified" ? @sprintf("%s", fmt_time(isfinite(r.t_warm) ? r.t_warm : r.t_first)) :
        r.status == "wrong" ? "\\wrong" : r.status == "unverified" ? "\\unv" : r.status == "unsolved" ? "\\unsolved" :
        r.status == "unavailable" ? "\\na" : r.status == "timeout" ? "T" : "E"
    open(joinpath(TABLES, "G_groebner.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables_G.jl from results/G_groebner_*.tsv")
        for c in cases
            rs = [rec(s, c) for s in G_SYSTEMS]
            ds = [digest(r) for r in rs if r !== nothing && r.status == "verified" && digest(r) != ""]
            agree = isempty(ds) ? "--" : string(maximum(count(==(d), ds) for d in unique(ds)), "/", length(ds))
            ks = filter(!isempty, [ksize(r) for r in rs if r !== nothing]); k = isempty(ks) ? "--" : ks[1]
            println(io, texesc(c), " & ", join(cell.(rs), " & "), " & ", k, " & ", agree, " \\\\")
        end
        println(io, "\\bottomrule")
    end
    # Coverage and digest agreement only; operation timing quartiles are in
    # the machine-readable per-operation metrics generated by make_tables.jl.
    open(joinpath(TABLES, "G_groebner_summary.tex"), "w") do io
        println(io, "% generated by make_tables_G.jl; verified/attempted and digest agreement")
        for system in G_SYSTEMS
            rows = [r for r in data[system] if r.idx > 0]
            isempty(rows) && continue
            verified = count(r -> r.status == "verified", rows)
            attempted = count(r -> r.status != "unavailable", rows)
            timeouts = count(r -> r.status == "timeout", rows)
            other = count(r -> r.status in ("error", "unverified", "unsolved", "wrong"), rows)
            agree = count(cases) do case
                r = rec(system, case)
                (r === nothing || r.status != "verified" || isempty(digest(r))) && return false
                others = [digest(rec(s2, case)) for s2 in G_SYSTEMS if s2 != system && rec(s2, case) !== nothing && rec(s2, case).status == "verified"]
                !isempty(others) && all(==(digest(r)), others)
            end
            println(io, join((G_LABEL[system], "$(verified)/$(attempted)", string(timeouts), string(other), string(agree)), " & "), " ", Char(92), Char(92))
        end
        println(io, "\\bottomrule")
    end
    println(md, "## G: Gröbner bases (warm seconds when verified; status otherwise; agreement of the digests)\n")
    println(md, "| case | ", join((G_LABEL[s] for s in G_SYSTEMS), " | "), " | size | agree |\n|---|", "---|"^(length(G_SYSTEMS) + 2))
    for c in cases
        rs = [rec(s, c) for s in G_SYSTEMS]
        ds = [digest(r) for r in rs if r !== nothing && r.status == "verified" && digest(r) != ""]
        agree = isempty(ds) ? "--" : string(maximum(count(==(d), ds) for d in unique(ds)), "/", length(ds))
        ks = filter(!isempty, [ksize(r) for r in rs if r !== nothing]); k = isempty(ks) ? "--" : ks[1]
        println(md, "| ", c, " | ", join((r === nothing ? "--" : r.status == "verified" ? @sprintf("%.4g s", isfinite(r.t_warm) ? r.t_warm : r.t_first) : r.status for r in rs), " | "), " | ", k, " | ", agree, " |")
    end
    println(md)
end

make_G()
