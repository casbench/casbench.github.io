# Tables of bench F (included by make_tables.jl).
#
# Output: tables/F_integration.tex, one row per test-file category (the first
# directory of the archive: for each system, verified/attempted and the A
# grade count. Per-operation time quartiles are in operation_metrics.tsv.

const F_SYSTEMS = ["giac", "symbolics", "sympy", "symj", "maxima", "fricas", "sage_giac", "sage_maxima", "sage_fricas", "sage_sympy", "computeengine"]
const F_LABEL = Dict("giac" => "Giac.jl", "symbolics" => "Symbolics.jl", "sympy" => "SymPy", "symj" => "SymJ.jl",
                     "maxima" => "Maxima", "fricas" => "FriCAS", "sage_giac" => "Sage/Giac", "sage_maxima" => "Sage/Maxima",
                     "sage_fricas" => "Sage/FriCAS", "sage_sympy" => "Sage/SymPy", "computeengine" => "Compute Engine")

function make_F()
    data = Dict(s => read_records(joinpath(RESULTS, "F_integration_$(s).tsv")) for s in F_SYSTEMS)
    systems = [s for s in F_SYSTEMS if !isempty(data[s])]
    isempty(systems) && return
    category(c) = (m = match(r"^\d+ (\d+_[^/:]+)", c); m === nothing ? "other" : replace(m[1], r"^\d+_" => "", "_" => " "))
    cases = String[]
    for s in systems, r in data[s]
        r.case == "_load" && continue
        r.case in cases || push!(cases, r.case)
    end
    cats = unique(category.(cases))
    grade(r) = (m = match(r"grade=([ABF])", r.note); m === nothing ? "" : m[1])
    rec(s, c) = (j = findfirst(r -> r.case == c, data[s]); j === nothing ? nothing : data[s][j])
    function stats(system, cs)
        rs = [rec(system, c) for c in cs]
        verified = count(r -> r !== nothing && r.status in ("verified", "verified_numeric"), rs)
        attempted = count(r -> r !== nothing && r.status != "unavailable", rs)
        grade_a = count(r -> r !== nothing && r.status in ("verified", "verified_numeric") && grade(r) == "A", rs)
        (verified, attempted, grade_a)
    end
    open(joinpath(TABLES, "F_integration.tex"), "w") do io
        println(io, "% generated by make_tables_F.jl; verified/attempted and grade A")
        for cat in cats
            cs = [c for c in cases if category(c) == cat]
            cells = [begin v, n, a = stats(system, cs); "$(v)/$(n) & $(a)" end for system in systems]
            println(io, texesc(cat), " & ", length(cs), " & ", join(cells, " & "), " ", Char(92), Char(92))
        end
        println(io, "\\bottomrule")
    end
    open(joinpath(TABLES, "F_integration_summary.tex"), "w") do io
        println(io, "% generated by make_tables_F.jl; verified/attempted and outcome counts")
        for system in systems
            rs = [rec(system, c) for c in cases]
            cnt(st) = count(r -> r !== nothing && r.status == st, rs)
            v, n, a = stats(system, cases)
            cells = (F_LABEL[system], "$(v)/$(n)", string(a), string(v-a), string(cnt("wrong")),
                     string(cnt("unsolved")), string(cnt("unverified")), string(cnt("error") + cnt("timeout")))
            println(io, join(cells, " & "), " ", Char(92), Char(92))
        end
        println(io, "\\bottomrule")
    end
    println(md, "## F: integration sample (verified / attempted; grade A)\n")
    println(md, "| category | cases | ", join((F_LABEL[system] for system in systems), " | "), " |\n|---|---|", "---|"^length(systems))
    for cat in cats
        cs = [c for c in cases if category(c) == cat]
        cells = [begin v, n, a = stats(system, cs); "$(v)/$(n); A=$(a)" end for system in systems]
        println(md, "| ", cat, " | ", length(cs), " | ", join(cells, " | "), " |")
    end
    println(md)

end

make_F()
