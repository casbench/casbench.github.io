# Tables of bench F (included by make_tables.jl).
#
# Output: tables/F_integration.tex, one row per test-file category (the first
# directory of the archive) and the total: for each system, the verified
# count, the A grade count (verified and not more than twice the reference's
# leaf count) and the median warm time over the verified cases.

const F_SYSTEMS = ["giac", "symbolics", "sympy", "symj", "maxima", "fricas", "sage_giac", "sage_maxima", "sage_fricas", "sage_sympy", "computeengine"]
const F_LABEL = Dict("giac" => "Giac.jl", "symbolics" => "Symbolics.jl", "sympy" => "SymPy", "symj" => "SymJ.jl",
                     "maxima" => "Maxima", "fricas" => "FriCAS", "sage_giac" => "Sage/Giac", "sage_maxima" => "Sage/Maxima",
                     "sage_fricas" => "Sage/FriCAS", "sage_sympy" => "Sage/SymPy", "computeengine" => "Compute Engine")

function make_F()
    data = Dict(s => read_records(joinpath(RESULTS, "F_integration_$(s).tsv")) for s in F_SYSTEMS)
    systems = [s for s in F_SYSTEMS if !isempty(data[s])]
    isempty(systems) && return
    category(c) = (m = match(r"^\d+ (\d+_[^/:]+)", c); m === nothing ? "other" : replace(m[1], r"^\d+_" => "", "_" => " "))
    cases = String[]
    for s in systems, r in data[s]
        r.case == "_load" && continue
        r.case in cases || push!(cases, r.case)
    end
    cats = unique(category.(cases))
    grade(r) = (m = match(r"grade=([ABF])", r.note); m === nothing ? "" : m[1])
    rec(s, c) = (j = findfirst(r -> r.case == c, data[s]); j === nothing ? nothing : data[s][j])
    function stats(s, cs)
        rs = [rec(s, c) for c in cs]
        v = count(r -> r !== nothing && r.status == "verified", rs)
        a = count(r -> r !== nothing && r.status == "verified" && grade(r) == "A", rs)
        ts = [isfinite(r.t_warm) ? r.t_warm : r.t_first for r in rs if r !== nothing && r.status == "verified"]
        (v, a, isempty(ts) ? NaN : median(ts))
    end
    open(joinpath(TABLES, "F_integration.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables_F.jl from results/F_integration_*.tsv")
        for cat in cats
            cs = [c for c in cases if category(c) == cat]
            cells = [begin (v, a, t) = stats(s, cs); @sprintf("%d & %d & %s", v, a, fmt_time(t)) end for s in systems]
            println(io, texesc(cat), " & ", length(cs), " & ", join(cells, " & "), " \\\\")
        end
        println(io, "\\midrule")
        cells = [begin (v, a, t) = stats(s, cases); @sprintf("%d & %d & %s", v, a, fmt_time(t)) end for s in systems]
        println(io, "\\textbf{All} & ", length(cases), " & ", join(cells, " & "), " \\\\")
        println(io, "\\bottomrule")
    end
    # one-line-per-system summary for the paper: verified, A, B, wrong, unsolved, unverified, error+timeout, median warm time
    open(joinpath(TABLES, "F_integration_summary.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables_F.jl from results/F_integration_*.tsv")
        for s in systems
            rs = [rec(s, c) for c in cases]
            cnt(st) = count(r -> r !== nothing && r.status == st, rs)
            v, a, t = stats(s, cases)
            println(io, F_LABEL[s], " & ", v, " & ", a, " & ", v - a, " & ", cnt("wrong"), " & ", cnt("unsolved"), " & ", cnt("unverified"),
                    " & ", cnt("error") + cnt("timeout"), " & ", fmt_time(t), " \\\\")
        end
        println(io, "\\bottomrule")
    end
    println(md, "## F: integration sample (verified / grade A / median warm time)\n")
    println(md, "| category | n | ", join((F_LABEL[s] for s in systems), " | "), " |\n|---|---|", "---|"^length(systems))
    for cat in [cats; "All"]
        cs = cat == "All" ? cases : [c for c in cases if category(c) == cat]
        println(md, "| ", cat, " | ", length(cs), " | ", join((begin (v, a, t) = stats(s, cs); @sprintf("%d / %d / %s", v, a, isfinite(t) ? @sprintf("%.3g s", t) : "--") end for s in systems), " | "), " |")
    end
    println(md)
end

make_F()
