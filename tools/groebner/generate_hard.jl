# Regenerate the fixed hard-tier strings with the pinned envs/groebner manifest.
# Usage: julia --project=envs/groebner tools/groebner/generate_hard.jl > G_groebner/hard_inputs.jl
using Groebner, AbstractAlgebra
println("# Generated by tools/groebner/generate_hard.jl using Groebner.jl Examples (GPL-2.0).")
println("const HARD_SYSTEMS = [")
for (name, f, budget) in (("cyclic8", () -> Groebner.Examples.cyclicn(8), 600),
                          ("cyclic9", () -> Groebner.Examples.cyclicn(9), 3600),
                          ("katsura10", () -> Groebner.Examples.katsuran(10), 600),
                          ("eco11", () -> Groebner.Examples.eco11(), 600),
                          ("eco12", () -> Groebner.Examples.eco12(), 600))
    polys = f()
    vars = string.(gens(parent(first(polys))))
    println("    (name = ", repr(name), ", vars = ", repr(vars), ", budget = ", budget, ", polys = [")
    for p in polys
        println("        ", repr(string(p)), ",")
    end
    println("    ]),")
end
println("]")
