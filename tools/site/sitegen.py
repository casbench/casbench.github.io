            out += f"[{title}](../) · operation `{esc(e['op'])}`"
            if key == "E_suite" and i in self.categories:
                out += f" · category *{esc(self.categories[i])}*"
            out += "\n\n"
            # the problem's own note is the one most systems share; error messages are each system's own
            notes = [] if key == "G_groebner" else [e[s]["note"] for s in systems if e[s]["note"] and not e[s]["note"].startswith(("check raised", "worker ", "rerun"))]
            asked = [n for n, _ in __import__("collections").Counter(notes).most_common(1)]
            if asked:
                out += f"**What is asked.** {esc(asked[0])}\n\n"
            verification = key in ("F_integration", "H_osr")
            groebner = key == "G_groebner"
            if groebner:
                out += ("Check time includes any checker compilation. Process peak RSS, where recorded, includes "
                        "the whole subprocess and is not directly comparable to an engine-only memory measurement.\n\n")
            out += "| system | status | first call | warm |" + (" self-check | verification time |" if verification else "") + (" basis size | terms | check time | process peak RSS |" if groebner else "") + "\n"
            out += "|---|---|---|---|" + ("---|---|" if verification else "") + ("---|---|---|---|" if groebner else "") + "\n"
            for s in systems:
                r = e[s]
                extra = ""
                if verification:
                    vs, vt = r.get("verify_status", ""), r.get("verify_time_s", math.nan)
                    extra = f" {badge(vs) if vs else 'not measured'} | {fmt_time(vt) if math.isfinite(vt) else '--'} |"
                if groebner:
                    note = r.get("note", "")
                    def metric(pattern):
                        match = re.search(pattern, note)
                        return match.group(1) if match else None
                    size = metric(r"\bk=(\d+)")
                    terms = metric(r"\bterms=(\d+)")
                    check = metric(r"\bcheck_wall_s=(\d+(?:\.\d*)?(?:[eE][+-]?\d+)?)")
                    rss = metric(r"\bprocess_peak_rss_kib=(\d+)")
                    check_display = fmt_time(float(check)) if check else "--"
                    extra = f" {size or '--'} | {terms or '--'} | {check_display} | {rss + ' KiB' if rss else '--'} |"
                out += f"| {esc(s)} | {badge(r['status'])} | {fmt_time(r['t_first_s'])} | {fmt_time(r['t_warm_s'])} |{extra}\n"
            out += "\n## Problem\n\n"
            tex = self.statement_tex(key, i, name)
            if tex:
                out += "$$" + tex + "$$\n\n"
            out += (f"{esc(asked[0])}\n\n" if asked else "") + (
                "The same problem is given to every system through its own adapter. For each system below, **Input** is what "
                "the benchmark sent (the system's own syntax, as recorded during the run; else the task or problem source the "
                "adapter runs) and **Output** is what came back. A status may hide a wrongly generated input, which is an error "
                "of the benchmark, not of the system.\n\n")
