# Turn results/*.tsv into the LaTeX table bodies (tables/*.tex, copied into the
# paper repository) and a Markdown summary (results/summary.md). Only the
# standard library is used.
#
#   julia benchmark/make_tables.jl

include(joinpath(@__DIR__, "lib", "common.jl"))
using .BenchCommon
using Printf

const RESULTS = joinpath(@__DIR__, "results")
const TABLES = get(ENV, "BENCH_TABLES_DIR", joinpath(@__DIR__, "tables"))   # LaTeX tables; the paper repository copies them
mkpath(TABLES)

texesc(s) = replace(string(s), "\\" => "\\textbackslash{}", "_" => "\\_", "%" => "\\%", "&" => "\\&", "#" => "\\#", "^" => "\\^{}")

fmt_time(t) = !isfinite(t) ? "--" :
    t < 1e-5 ? @sprintf("%.1f\\,\\textmu s", t * 1e6) :
    t < 1e-3 ? @sprintf("%.0f\\,\\textmu s", t * 1e6) :
    t < 1 ? @sprintf("%.1f\\,ms", t * 1e3) : @sprintf("%.2f\\,s", t)
fmt_us(t) = isfinite(t) ? @sprintf("%.1f", t * 1e6) : "--"

const STATUS_MARK = Dict("verified" => "\\ok", "wrong" => "\\wrong", "unverified" => "\\unv",
                         "unsolved" => "\\unsolved", "unavailable" => "\\na", "error" => "\\err", "timeout" => "\\tmo")

md = IOBuffer()
println(md, "# Benchmark summary\n\nGenerated by make_tables.jl from results/*.tsv.\n")

# ---------------------------------------------------------------- A: FFI overhead
let recs = read_records(joinpath(RESULTS, "A_ffi_giac.tsv"))
    if !isempty(recs)
        levels = ["binding", "tier1", "invoke_fast", "invoke_str", "giac_eval"]
        cases = unique(r.case for r in recs)
        open(joinpath(TABLES, "A_ffi.tex"), "w") do io
            println(io, "% generated by benchmark/make_tables.jl from results/A_ffi_giac.tsv")
            for c in cases
                row = [texesc(replace(c, r" \[.*\]" => ""))]   # drop the bracketed remark of the case name
                for l in levels
                    r = findfirst(x -> x.case == c && x.op == l, recs)
                    push!(row, r === nothing ? "--" : fmt_us(recs[r].t_warm))
                end
                println(io, join(row, " & "), " \\\\")
            end
            println(io, "\\bottomrule")
        end
        println(md, "## A: FFI overhead (microseconds per call, min over rounds)\n")
        println(md, "| case | ", join(levels, " | "), " |\n|---|", "---|"^length(levels))
        for c in cases
            vals = [(r = findfirst(x -> x.case == c && x.op == l, recs); r === nothing ? "--" : fmt_us(recs[r].t_warm)) for l in levels]
            println(md, "| ", c, " | ", join(vals, " | "), " |")
        end
        println(md)
    end
end

# ---------------------------------------------------------------- B and D: per system
function per_system_table(bench, systems, texname, mdtitle; with_times = true)
    data = Dict(s => read_records(joinpath(RESULTS, "$(bench)_$(s).tsv")) for s in systems)
    any(!isempty, values(data)) || return
    cases = String[]
    for s in systems, r in data[s]
        r.idx > 0 && !(r.case in cases) && push!(cases, r.case)
    end
    open(joinpath(TABLES, "$(texname).tex"), "w") do io
        println(io, "% generated by benchmark/make_tables.jl from results/$(bench)_*.tsv")
        for c in cases
            row = [texesc(c)]
            for s in systems
                r = findfirst(x -> x.case == c, data[s])
                if r === nothing
                    push!(row, "--")
                else
                    rec = data[s][r]
                    cell = get(STATUS_MARK, rec.status, rec.status)
                    with_times && rec.status in ("verified", "wrong", "unverified", "unsolved") &&
                        (cell *= " " * fmt_time(isfinite(rec.t_warm) ? rec.t_warm : rec.t_first))
                    push!(row, cell)
                end
            end
            println(io, join(row, " & "), " \\\\")
        end
        println(io, "\\bottomrule")
    end
    # summary counts
    open(joinpath(TABLES, "$(texname)_summary.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables.jl")
        for s in systems
            recs = filter(r -> r.idx > 0, data[s])
            isempty(recs) && continue
            nv = count(r -> r.status == "verified", recs)
            nw = count(r -> r.status == "wrong", recs)
            nu = count(r -> r.status in ("unsolved", "unverified"), recs)
            nn = count(r -> r.status == "unavailable", recs)
            ne = count(r -> r.status in ("error", "timeout"), recs)
            load = findfirst(r -> r.case == "_load", data[s])
            tl = load === nothing ? NaN : data[s][load].t_first
            tf = sum(r.t_first for r in recs if isfinite(r.t_first); init = 0.0)
            tw = sum(r.t_warm for r in recs if isfinite(r.t_warm); init = 0.0)
            println(io, texesc(s), " & ", nv, " & ", nw, " & ", nu, " & ", nn, " & ", ne, " & ",
                    fmt_time(tl), " & ", fmt_time(tf), " & ", fmt_time(tw), " \\\\")
        end
        println(io, "\\bottomrule")
    end
    println(md, "## ", mdtitle, "\n")
    println(md, "| case | ", join(systems, " | "), " |\n|---|", "---|"^length(systems))
    for c in cases
        vals = map(systems) do s
            r = findfirst(x -> x.case == c, data[s])
            r === nothing ? "--" : (rec = data[s][r]; rec.status * (isfinite(rec.t_warm) ? @sprintf(" (%.3g s)", rec.t_warm) : ""))
        end
        println(md, "| ", c, " | ", join(vals, " | "), " |")
    end
    println(md)
end

per_system_table("B_cas", ["giac", "symbolics", "sympy", "symj", "symengine"], "B_cas", "B: CAS operations")
per_system_table("D_coverage", ["giac", "symbolics", "sympy", "symj", "symengine"], "D_coverage", "D: functional coverage"; with_times = false)

# ---------------------------------------------------------------- C: integer factorisation
let systems = ["giac", "primes", "pari"]
    data = Dict(s => read_records(joinpath(RESULTS, "C_ifactor_$(s).tsv")) for s in systems)
    if any(!isempty, values(data))
        cases = String[]
        for s in systems, r in data[s]
            r.idx > 0 && !(r.case in cases) && push!(cases, r.case)
        end
        open(joinpath(TABLES, "C_ifactor.tex"), "w") do io
            println(io, "% generated by benchmark/make_tables.jl from results/C_ifactor_*.tsv")
            for c in cases
                row = [texesc(c)]
                for s in systems
                    r = findfirst(x -> x.case == c, data[s])
                    if r === nothing
                        push!(row, "--")
                    else
                        rec = data[s][r]
                        push!(row, rec.status == "verified" ? fmt_time(isfinite(rec.t_warm) ? rec.t_warm : rec.t_first) :
                                   get(STATUS_MARK, rec.status, rec.status))
                    end
                end
                println(io, join(row, " & "), " \\\\")
            end
            println(io, "\\bottomrule")
        end
        println(md, "## C: integer factorisation (seconds, min over repeats; status otherwise)\n")
        println(md, "| case | ", join(systems, " | "), " |\n|---|---|---|---|")
        for c in cases
            vals = map(systems) do s
                r = findfirst(x -> x.case == c, data[s])
                r === nothing ? "--" : (rec = data[s][r]; rec.status == "verified" ? @sprintf("%.3g", isfinite(rec.t_warm) ? rec.t_warm : rec.t_first) : rec.status)
            end
            println(md, "| ", c, " | ", join(vals, " | "), " |")
        end
        println(md)
    end
end

