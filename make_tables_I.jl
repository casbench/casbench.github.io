# Table of bench I (included by make_tables.jl): tables/I_scale.tex, one row
# per workload, the warm time of each system when verified (else its status).
# For the code generation rows the warm time is the time of the thousand
# calls and the first-call time includes the compilation.

const I_SYSTEMS = ["giac", "symbolics", "symengine", "symj", "sympy", "computeengine"]
const I_LABEL = Dict("giac" => "Giac.jl", "symbolics" => "Symbolics.jl", "symengine" => "SymEngine.jl", "symj" => "SymJ.jl", "sympy" => "SymPy", "computeengine" => "Compute Engine")

function make_I()
    data = Dict(s => read_records(joinpath(RESULTS, "I_scale_$(s).tsv")) for s in I_SYSTEMS)
    systems = [s for s in I_SYSTEMS if !isempty(data[s])]
    isempty(systems) && return
    cases = String[]
    for s in systems, r in data[s]
        r.case == "_load" && continue
        r.case in cases || push!(cases, r.case)
    end
    rec(s, c) = (j = findfirst(r -> r.case == c, data[s]); j === nothing ? nothing : data[s][j])
    cell(r) = r === nothing ? "--" :
        r.status == "verified" ? fmt_time(isfinite(r.t_warm) ? r.t_warm : r.t_first) :
        r.status == "wrong" ? "\\wrong" : r.status == "unverified" ? "\\unv" : r.status == "unsolved" ? "\\unsolved" :
        r.status == "unavailable" ? "\\na" : r.status == "timeout" ? "T" : "E"
    open(joinpath(TABLES, "I_scale.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables_I.jl from results/I_scale_*.tsv")
        # short labels for the paper's column width (the full case names stay in the results and on the site)
        short(c) = replace(c, r"^substitute a -> 2 sin b, tree of (\d+) leaves$" => s"subs, \1 leaves",
                              r"^evaluate tree of (\d+) leaves at a point$" => s"eval, \1 leaves",
                              r"^compile tree of (\d+) leaves, 1000 calls$" => s"compile, \1 leaves",
                              r"^d/dx expand\(\((.*)\)\^50\)$" => s"d/dx expand (\1)^50",
                              r"^series sin\(cos\(1\+x\)\), order 15$" => "series sin(cos(1+x)), 15")
        for c in cases
            println(io, texesc(short(c)), " & ", join((cell(rec(s, c)) for s in systems), " & "), " \\\\")
        end
        println(io, "\\bottomrule")
    end
    println(md, "## I: throughput at scale (warm seconds when verified; status otherwise)\n")
    println(md, "| workload | ", join((I_LABEL[s] for s in systems), " | "), " |\n|---|", "---|"^length(systems))
    for c in cases
        cells = [(r = rec(s, c); r === nothing ? "--" : r.status == "verified" ? @sprintf("%.4g s", isfinite(r.t_warm) ? r.t_warm : r.t_first) : r.status) for s in systems]
        println(md, "| ", c, " | ", join(cells, " | "), " |")
    end
    println(md)
end

make_I()
