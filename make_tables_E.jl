# Tables and the dot plot of bench E (included by make_tables.jl).
#
# Outputs
#   paper/tables/E_suite_giac_sympy.tex   per category: solved by Giac.jl / by SymPy / both,
#                                         faster counts and the median time ratio (image-1 style)
#   paper/tables/E_suite_systems.tex      per category and system: median ratio to the fastest
#                                         system, answered count, fastest count (image-3 style)
#   paper/figures/E_times.tex             pgfplots dot plot of every problem's time, hollow = not solved
#
# Times are the warm times (minimum over repeats) when measured, else the first call.

using Statistics: median

const E_SYSTEMS = ["giac", "symbolics", "sympy", "symj"]
const E_LABEL = Dict("giac" => "Giac.jl", "symbolics" => "Symbolics.jl", "sympy" => "SymPy", "symj" => "SymJ.jl")
solved(r) = r.status == "verified"
etime(r) = isfinite(r.t_warm) ? r.t_warm : r.t_first

function make_E()
    data = Dict(s => read_records(joinpath(RESULTS, "E_suite_$(s).tsv")) for s in E_SYSTEMS)
    any(!isempty, values(data)) || return
    # problem order and categories from the problem file (names only, no system loaded)
    cats = String[]; names = String[]; catof = Dict{String,String}()
    for line in eachline(joinpath(@__DIR__, "E_suite", "problems.jl"))
        m = match(r"^\s+P\(CAT\[(\d+)\], \"([^\"]+)\"", line)
        m === nothing && continue
        push!(names, m[2]); push!(cats, m[1]); catof[m[2]] = m[1]
    end
    catnames = Dict{String,String}()
    for line in eachline(joinpath(@__DIR__, "E_suite", "problems.jl"))
        m = match(r"^const CAT = \[(.*)$", line)
        m === nothing && continue
        allcats = String[]
        for part in eachline(IOBuffer(replace(read(joinpath(@__DIR__, "E_suite", "problems.jl"), String), r"(?s).*const CAT = \[" => "", r"(?s)\]\n.*" => "")))
            for q in eachmatch(r"\"([^\"]+)\"", part)
                push!(allcats, q[1])
            end
        end
        for (i, cname) in enumerate(allcats)
            catnames[string(i)] = cname
        end
        break
    end
    # records are matched by position, since two problems share the name "A polylogarithm value"
    rec(s, i::Int) = (j = findfirst(r -> r.idx == i, data[s]); j === nothing ? nothing : data[s][j])
    catids = unique(cats)

    # ---- Giac vs SymPy table
    open(joinpath(TABLES, "E_suite_giac_sympy.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables_E.jl from results/E_suite_*.tsv")
        tot = zeros(Int, 5); allratios = Float64[]; ntot = 0
        for cid in catids
            nm = [i for (i, c) in enumerate(cats) if c == cid]
            g = [rec("giac", i) for i in nm]; p = [rec("sympy", i) for i in nm]
            sg = count(r -> r !== nothing && solved(r), g); sp = count(r -> r !== nothing && solved(r), p)
            both = [(a, b) for (a, b) in zip(g, p) if a !== nothing && b !== nothing && solved(a) && solved(b)]
            fg = count(((a, b),) -> etime(a) < etime(b), both); fp = count(((a, b),) -> etime(b) < etime(a), both)
            ratios = [etime(b) / etime(a) for (a, b) in both]
            append!(allratios, ratios)
            tot .+= [sg, sp, length(both), fg, fp]; ntot += length(nm)
            med = isempty(ratios) ? "--" : (m = median(ratios); m >= 1 ? @sprintf("Giac.jl %.1f\\texttimes{} faster", m) : @sprintf("SymPy %.1f\\texttimes{} faster", 1 / m))
            println(io, texesc(catnames[cid]), " & ", sg, " of ", length(nm), " & ", sp, " of ", length(nm), " & ", length(both), " & ", fg, " & ", fp, " & ", med, " \\\\")
        end
        println(io, "\\midrule")
        med = isempty(allratios) ? "--" : (m = median(allratios); m >= 1 ? @sprintf("Giac.jl %.1f\\texttimes{} faster", m) : @sprintf("SymPy %.1f\\texttimes{} faster", 1 / m))
        println(io, "\\textbf{All problems} & ", tot[1], " of ", ntot, " & ", tot[2], " of ", ntot, " & ", tot[3], " & ", tot[4], " & ", tot[5], " & ", med, " \\\\")
        println(io, "\\bottomrule")
    end

    # ---- four-system table: per category, ratio to the fastest, answered, fastest
    open(joinpath(TABLES, "E_suite_systems.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables_E.jl from results/E_suite_*.tsv")
        totals = Dict(s => (Float64[], 0, 0) for s in E_SYSTEMS)
        tot_ans = Dict(s => 0 for s in E_SYSTEMS); tot_fast = Dict(s => 0 for s in E_SYSTEMS); tot_rat = Dict(s => Float64[] for s in E_SYSTEMS)
        ntot = 0
        for cid in catids
            nm = [i for (i, c) in enumerate(cats) if c == cid]
            ntot += length(nm)
            cells = String[]
            for s in E_SYSTEMS
                rs = [rec(s, i) for i in nm]
                ans = count(r -> r !== nothing && solved(r), rs)
                ratios = Float64[]; fastest = 0
                for (ii, pi_) in enumerate(nm)
                    r = rs[ii]
                    (r === nothing || !solved(r)) && continue
                    others = [rec(s2, pi_) for s2 in E_SYSTEMS]
                    best = minimum(etime(o) for o in others if o !== nothing && solved(o))
                    push!(ratios, etime(r) / best)
                    etime(r) == best && (fastest += 1)
                end
                append!(tot_rat[s], ratios); tot_ans[s] += ans; tot_fast[s] += fastest
                push!(cells, isempty(ratios) ? "-- & $ans of $(length(nm)), $fastest fastest" :
                             @sprintf("\\texttimes%.1f & %d of %d, %d fastest", median(ratios), ans, length(nm), fastest))
            end
            println(io, texesc(catnames[cid]), " & ", join(cells, " & "), " \\\\")
        end
        println(io, "\\midrule")
        cells = [isempty(tot_rat[s]) ? "-- & $(tot_ans[s]) of $ntot, $(tot_fast[s]) fastest" :
                 @sprintf("\\texttimes%.1f & %d of %d, %d fastest", median(tot_rat[s]), tot_ans[s], ntot, tot_fast[s]) for s in E_SYSTEMS]
        println(io, "\\textbf{All problems} & ", join(cells, " & "), " \\\\")
        println(io, "\\bottomrule")
    end

    # ---- dot plot (pgfplots): one row per problem, log time axis, hollow = not solved
    mkpath(joinpath(@__DIR__, "..", "paper", "figures"))
    open(joinpath(@__DIR__, "..", "paper", "figures", "E_times.tex"), "w") do io
        println(io, "% generated by benchmark/make_tables_E.jl from results/E_suite_*.tsv")
        N = length(names)
        println(io, "\\begin{tikzpicture}")
        println(io, "\\begin{axis}[xmode=log, width=0.60\\textwidth, height=", round(0.11 * N + 1.5; digits = 1), "cm,")
        println(io, "  xmin=5e-6, xmax=200, xlabel={seconds}, ytick={1,...,", N, "}, y dir=reverse, ymin=0.5, ymax=", N + 0.5, ",")
        println(io, "  yticklabels={", join([texesc(n) for n in names], ","), "}, yticklabel style={font=\\tiny}, tick label style={font=\\scriptsize},")
        println(io, "  xlabel style={font=\\scriptsize}, grid=major, grid style={gray!30}, legend style={font=\\scriptsize, at={(0.5,1.01)}, anchor=south, legend columns=4},")
        println(io, "  clip=false, every axis plot/.append style={only marks}]")
        marks = Dict("giac" => "*", "sympy" => "square*", "symbolics" => "triangle*", "symj" => "diamond*")
        hollow = Dict("giac" => "o", "sympy" => "square", "symbolics" => "triangle", "symj" => "diamond")
        colors = Dict("giac" => "orange!90!black", "sympy" => "cyan!70!black", "symbolics" => "violet", "symj" => "green!60!black")
        for s in E_SYSTEMS
            print(io, "\\addplot[mark=", marks[s], ", mark size=1.2pt, color=", colors[s], "] coordinates {")
            for (i, n) in enumerate(names)
                r = rec(s, i)
                (r === nothing || !solved(r)) && continue
                print(io, "(", @sprintf("%.3g", max(etime(r), 5e-6)), ",", i, ")")
            end
            println(io, "};")
            println(io, "\\addlegendentry{", E_LABEL[s], "}")
            print(io, "\\addplot[mark=", hollow[s], ", mark size=1.2pt, color=", colors[s], ", forget plot] coordinates {")
            for (i, n) in enumerate(names)
                r = rec(s, i)
                (r === nothing || solved(r) || r.status == "unavailable") && continue
                tt = isfinite(etime(r)) ? etime(r) : 100.0
                print(io, "(", @sprintf("%.3g", max(tt, 5e-6)), ",", i, ")")
            end
            println(io, "};")
        end
        # category separators and labels on the right
        prev = ""; start = 1
        for (i, c) in enumerate(cats)
            if c != prev
                i > 1 && println(io, "\\draw[gray!60] (axis cs:5e-6,", i - 0.5, ") -- (axis cs:200,", i - 0.5, ");")
                prev = c; start = i
            end
            if i == N || cats[i + 1] != c
                println(io, "\\node[anchor=west, font=\\tiny, text=gray!80!black] at (axis cs:200,", (start + i) / 2, ") {", texesc(catnames[c]), "};")
            end
        end
        println(io, "\\end{axis}")
        println(io, "\\end{tikzpicture}")
    end

    # ---- markdown summary
    println(md, "## E: problem suite\n")
    println(md, "| problem | category | ", join(E_SYSTEMS, " | "), " |\n|---|---|", "---|"^length(E_SYSTEMS))
    for (i, (n, c)) in enumerate(zip(names, cats))
        cells = map(E_SYSTEMS) do s
            r = rec(s, i)
            r === nothing ? "--" : (r.status * (isfinite(etime(r)) ? @sprintf(" (%.3g s)", etime(r)) : ""))
        end
        println(md, "| ", n, " | ", catnames[c], " | ", join(cells, " | "), " |")
    end
    println(md)
end

make_E()
